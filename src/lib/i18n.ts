export type TranslationKey = keyof (typeof translations)["en"];

export function getT(lang: Language) {
  return (key: TranslationKey): string => {
    const dict = translations[lang] as Record<string, string>;
    return dict[key] ?? (translations.en as Record<string, string>)[key] ?? key;
  };
}

/** Pick localized field by language. */
export function tx(
  field: { en: string; fa: string } | undefined | null,
  lang: Language
): string {
  if (!field) return "";
  return lang === "fa" ? field.fa : field.en;
}

/** Interpolate simple {n} placeholders. */
export function formatTemplate(tpl: string, vars: Record<string, string | number>) {
  return Object.entries(vars).reduce(
    (acc, [k, v]) => acc.replaceAll(`{${k}}`, String(v)),
    tpl
  );
}
